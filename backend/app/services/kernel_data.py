def set_primary(kernel_id: str) -> bool:
    """把某个内核设为主力（演示用，进程内状态）"""
    global PRIMARY_ID
    if kernel_id not in {e.id for e in _engines()}:
        return False
    PRIMARY_ID = kernel_id
    return True


